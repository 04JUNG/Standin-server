def recipe_for(scene):
    height, left, right = STANCES[scene["stance"]]
    height += scene.get("height", 0)
    recipe = {
        "id": scene["id"],
        "label": scene["label"],
        "hip_height": height,
        "root_xyz": scene.get("root_xyz", [0, 0, 0]),
        "spine_pitch": scene.get("lean", 0),
        "head_yaw": scene.get("look", 0),
        "head_pitch": scene.get("nod", 0),
        "left_leg": [list(left), [0.27, 0.40, 0.58]],
        "right_leg": [list(right), [-0.27, 0.40, 0.58]],
        "left_foot": {"mode": "planted"},
        "right_foot": {"mode": "planted"},
    }
    if scene["stance"] == "kneel":
        recipe["right_leg"][1] = [-0.17, 0.03, 0.05]
        recipe["right_foot"] = {"mode": "follow_shin", "pitch_degrees": 25}
    if scene["stance"] == "tiptoe":
        for side in ("left", "right"):
            recipe[side + "_foot"] = {"mode": "planted", "pitch_degrees": 25}
    wrists = deepcopy(GESTURES[scene["gesture"]])
    for i, side in enumerate(("left", "right")):
        target = list(scene.get(side + "_wrist", wrists[i]))
        target[1] += height
        sign = 1 if side == "left" else -1
        pole = scene.get(side + "_pole", [sign * 0.51, 0.28, 0.18])
        pole = [pole[0], pole[1] + height, pole[2]]
        recipe[side + "_arm"] = [target, pole]
    recipe.update(deepcopy(scene.get("overrides", {})))
    if scene["gesture"] == "spear_thrust" and "root_xyz" not in scene:
        recipe["root_xyz"] = [0, -25, 0]
    return recipe
